// Helper function to filter properties
export const filterProperties = ({ type, city, page = 1, limit = 8 }) => {
  let filtered = [...mockProperties];

  console.log('🔍 Filtering properties:', { type, city, page, limit });
  console.log('📦 Total properties before filter:', filtered.length);

  // Filter by type
  if (type && type !== "all" && type !== "") {
    const typeToMatch = type.toLowerCase().trim();
    
    filtered = filtered.filter((prop) => {
      const propType = prop.type.toLowerCase().trim();
      
      // Handle different type variations
      if (typeToMatch === "home/house") {
        return propType === "home/house" || 
               propType === "villa" || 
               propType === "independent house" ||
               propType === "apartment";
      }
      
      if (typeToMatch === "pg/hostel") {
        return propType === "pg/hostel" || 
               propType === "pg" || 
               propType === "hostel";
      }
      
      return propType === typeToMatch;
    });
  }

  console.log('📦 After type filter:', filtered.length);

  // Filter by city
  if (city && city !== "all" && city !== "") {
    filtered = filtered.filter((prop) => 
      prop.city.toLowerCase() === city.toLowerCase()
    );
  }

  console.log('📦 After city filter:', filtered.length);

  // Pagination
  const startIndex = (page - 1) * limit;
  const endIndex = startIndex + limit;
  const paginatedData = filtered.slice(startIndex, endIndex);

  const result = {
    data: paginatedData,
    hasNextPage: endIndex < filtered.length,
    pagination: {
      currentPage: page,
      totalPages: Math.ceil(filtered.length / limit),
      totalItems: filtered.length,
      hasNextPage: endIndex < filtered.length,
      hasPreviousPage: page > 1
    }
  };

  console.log('📦 Final result:', result);
  return result;
};

